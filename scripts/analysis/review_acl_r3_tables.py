#!/usr/bin/env python3
"""LaTeX tables for the ACL review-round-3 analyses (selection correction, gap decomposition).

Reads scripts/analysis/review_acl_r3_stats.json; writes acl2027/tables/tab_r3_selection.tex and
acl2027/tables/tab_r3_decomp.tex. No computation beyond formatting.
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TAB = os.path.join(ROOT, "acl2027", "tables")
V2M = ["Qwen2.5-VL-7B", "Qwen2.5-VL-32B", "Qwen3-VL-8B", "InternVL2-4B", "InternVL2-8B",
       "InternVL2.5-8B (6 tiles)"]
SEVEN = ["GPT-4o", "Gemini-2.0-Flash", "Gemini-2.5-Flash", "Claude Sonnet 4", "Qwen2.5-VL-7B",
         "Qwen2.5-VL-32B", "InternVL2.5-8B"]
CQ = (("qwen", "Qwen2.5-VL-7B"), ("qwen3vl8b", "Qwen3-VL-8B"))


def f(x):
    return f"{x:.1f}".replace("-", "$-$")


def cell(e, naive_ci=None):
    """naive [ci] | crossfit [ci] | max-stat [ci]. naive_ci overrides the naive interval with
    the one already reported in the paper (chartqa_gap_noscatter.json), so that one gap never
    carries two intervals."""
    n, cf, cb, rs = e["naive"], e["split_half"]["crossfit"], e["crossfit_boot"], e["reselect_boot"]
    lo, hi = naive_ci if naive_ci else (n["lo"], n["hi"])
    return (f"{f(n['est'])} [{f(lo)}, {f(hi)}] & {f(cf['mean'])} "
            f"[{f(cb['lo'])}, {f(cb['hi'])}] & {f(rs['bias_corrected'])} "
            f"[{f(rs['lo'])}, {f(rs['hi'])}]")


def main() -> None:
    d = json.load(open(os.path.join(HERE, "review_acl_r3_stats.json")))
    s1 = d["s1_selection"]
    qg = json.load(open(os.path.join(HERE, "chartqa_gap_noscatter.json")))
    rows = []
    for m in V2M:
        for md in ("tabular", "graph"):
            e = s1["v2"][m][md]
            rows.append(f"Expressive & {m.replace(' (6 tiles)', '')} & {md} ({e['n_q']}) & "
                        f"{cell(e)} \\\\")
    rows.append("\\midrule")
    for k, lab in CQ:
        for g, gl in (("gap5", "Gap"), ("gap4", "Gap$_4$")):
            e = s1["chartqa"][k][g]
            ci = qg[k]["ci"] if g == "gap4" else None
            rows.append(f"ChartQA & {lab} & {gl} ({e['n_q']}) & {cell(e, ci)} \\\\")
    body = "\n".join(rows)
    with open(os.path.join(TAB, "tab_r3_selection.tex"), "w") as fh:
        fh.write("% Generated by scripts/analysis/review_acl_r3_tables.py; do not edit by hand.\n"
                 "\\begin{tabular}{lllccc}\n\\toprule\n"
                 "Suite & Model & Cell ($n$) & Naive gap [95\\% CI] & Cross-fitted [CI] & "
                 "Max-statistic, bias-corr.\\ [CI] \\\\\n\\midrule\n"
                 f"{body}\n\\bottomrule\n\\end{{tabular}}\n")
    s2 = d["s2_decomposition"]["models"]
    rows = []
    for m in SEVEN:
        p = s2[m]["pooled"]
        parts = []
        for k in ("w_A_b_VD", "both_VD", "both_A", "other"):
            parts.append(f"{f(p[k]['est'])}")
        w = p["w_A_b_VD"]
        rows.append(f"{m} & {f(w['est'])} [{f(w['lo'])}, {f(w['hi'])}] & "
                    f"{' & '.join(parts[1:])} \\\\")
    with open(os.path.join(TAB, "tab_r3_decomp.tex"), "w") as fh:
        fh.write("% Generated by scripts/analysis/review_acl_r3_tables.py; do not edit by hand.\n"
                 "\\begin{tabular}{lcccc}\n\\toprule\n"
                 "Model & Worst A, best V/D [CI] & Both V/D & Both A & Other \\\\\n\\midrule\n"
                 + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


if __name__ == "__main__":
    main()
